create table if not exists public.articles (
    id bigint generated by default as identity primary key,
    url text not null unique,
    title text not null,
    description text,
    content_excerpt text,
    image_url text,
    source_name text,
    source_url text,
    published_at timestamptz,
    fetched_at timestamptz not null default now(),
    raw_payload jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now()
);

create index if not exists articles_published_at_idx
    on public.articles (published_at desc);
create index if not exists articles_source_name_idx
    on public.articles (source_name);

alter table public.articles enable row level security;

grant select on table public.articles to anon, authenticated;
grant select, insert, update on table public.articles to service_role;

drop policy if exists "Public read access to published article metadata"
    on public.articles;
create policy "Public read access to published article metadata"
    on public.articles
    for select
    to anon, authenticated
    using (true);
